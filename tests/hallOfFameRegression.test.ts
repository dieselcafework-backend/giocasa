import http from 'http';
import express from 'express';
import { dbService } from '../server/db';
import adminTournamentsRouter from '../server/routes/adminTournaments';

async function runTests() {
  console.log('🧪 Starting GioCasa Hall of Fame Regression & Validation Test Suite...\n');

  // 1. Initialize DB Service
  await dbService.init();

  // 2. Setup an isolated Express application mounting the admin router
  const app = express();
  app.use(express.json());
  app.use('/api/admin', adminTournamentsRouter);

  const server = http.createServer(app);
  await new Promise<void>((resolve) => server.listen(0, resolve));
  const port = (server.address() as any).port;
  const baseUrl = `http://localhost:${port}`;
  const adminPasscode = await dbService.getAdminPasscode();

  let allPassed = true;
  const assert = (condition: boolean, testName: string, detail?: string) => {
    if (condition) {
      console.log(`  ✅ PASS: ${testName}`);
    } else {
      console.error(`  ❌ FAIL: ${testName} ${detail ? `- ${detail}` : ''}`);
      allPassed = false;
    }
  };

  try {
    const targetHofId = 'hof-ayodhya-fc24-inaugural';
    const originalEntry = await dbService.getHallOfFameEntry(targetHofId);
    if (!originalEntry) {
      throw new Error(`Target entry ${targetHofId} not found in database!`);
    }
    const expectedMongoId = String(originalEntry._id);
    console.log(`📌 Baseline Entry found: id="${targetHofId}", _id="${expectedMongoId}"\n`);

    // =========================================================================
    // TEST 1: REGRESSION TEST WITH OBSERVED IMMUTABLE _id PAYLOAD
    // =========================================================================
    console.log('👉 [Test 1] Regression Test: PUT with immutable _id and client-supplied database fields');
    const updatePayload = {
      _id: '6acc98e4522345216441737b',
      id: targetHofId,
      playerName: 'Dhruv Sharma',
      award: 'Champion',
      eventDate: '2026-03-29',
      gameTitle: 'EA Sports FC 24',
      photoUrl: 'https://images.unsplash.com/photo-1542751371-adc38448a05e?auto=format&fit=crop&w=800&q=80',
      scoreDescription: 'Historic 4-2 grand final victory with undefeated bracket run.',
      isFeatured: true,
      isPublished: true,
      order: 1,
      createdAt: '1999-01-01T00:00:00.000Z', // Client-supplied timestamp should be ignored
      updatedAt: '1999-01-01T00:00:00.000Z', // Client-supplied timestamp should be ignored
      __v: 0,
    };

    const res1 = await fetch(`${baseUrl}/api/admin/hall-of-fame/${targetHofId}`, {
      method: 'PUT',
      headers: {
        'Content-Type': 'application/json',
        'x-admin-passcode': adminPasscode,
      },
      body: JSON.stringify(updatePayload),
    });

    const body1 = await res1.json();
    assert(res1.status === 200, 'HTTP status is 200 OK', `Received ${res1.status}: ${JSON.stringify(body1)}`);
    assert(body1.success === true, 'Response payload has success: true');
    assert(body1.data.playerName === 'Dhruv Sharma', 'Player name updated to "Dhruv Sharma"');
    assert(body1.data.award === 'Champion', 'Award updated to "Champion"');
    assert(body1.data.eventDate === '2026-03-29', 'Event date updated to "2026-03-29"');
    assert(body1.data.scoreDescription === 'Historic 4-2 grand final victory with undefeated bracket run.', 'Score description updated');

    // Verify database persistence and that _id remained untouched
    const freshEntry = await dbService.getHallOfFameEntry(targetHofId);
    assert(!!freshEntry, 'Fresh entry retrieved from database');
    if (freshEntry) {
      assert(String(freshEntry._id) === expectedMongoId, `MongoDB _id remained intact ("${expectedMongoId}")`);
      assert(freshEntry.playerName === 'Dhruv Sharma', 'Persistence confirmed: Player name is "Dhruv Sharma"');
      assert(freshEntry.award === 'Champion', 'Persistence confirmed: Award is "Champion"');
      assert(freshEntry.eventDate === '2026-03-29', 'Persistence confirmed: Event date is "2026-03-29"');
      assert(freshEntry.createdAt !== '1999-01-01T00:00:00.000Z', 'Database createdAt was preserved and not overwritten by client timestamp');
      assert(freshEntry.updatedAt !== '1999-01-01T00:00:00.000Z', 'Database updatedAt was generated by backend and not client timestamp');
      assert(new Date(freshEntry.updatedAt).getTime() > Date.now() - 60000, 'Database updatedAt is a recent timestamp');
    }

    console.log('\n👉 [Test 2] Invalid Payloads Validation');
    // Test 2a: Empty player name
    const res2a = await fetch(`${baseUrl}/api/admin/hall-of-fame/${targetHofId}`, {
      method: 'PUT',
      headers: {
        'Content-Type': 'application/json',
        'x-admin-passcode': adminPasscode,
      },
      body: JSON.stringify({ playerName: '   ' }),
    });
    const body2a = await res2a.json();
    assert(res2a.status === 400, 'Empty playerName returns 400 Bad Request');
    assert(body2a.success === false, 'Empty playerName response has success: false');

    // Test 2b: Invalid order (non-number)
    const res2b = await fetch(`${baseUrl}/api/admin/hall-of-fame/${targetHofId}`, {
      method: 'PUT',
      headers: {
        'Content-Type': 'application/json',
        'x-admin-passcode': adminPasscode,
      },
      body: JSON.stringify({ order: 'first' }),
    });
    const body2b = await res2b.json();
    assert(res2b.status === 400, 'Non-number order returns 400 Bad Request');
    assert(body2b.success === false, 'Invalid order response has success: false');

    // Test 2c: Non-object body (array)
    const res2c = await fetch(`${baseUrl}/api/admin/hall-of-fame/${targetHofId}`, {
      method: 'PUT',
      headers: {
        'Content-Type': 'application/json',
        'x-admin-passcode': adminPasscode,
      },
      body: JSON.stringify(['invalid_array']),
    });
    const body2c = await res2c.json();
    assert(res2c.status === 400, 'Non-object body returns 400 Bad Request');
    assert(body2c.success === false, 'Non-object response has success: false');

    console.log('\n👉 [Test 3] Unauthorized Requests');
    // Test 3a: Missing admin passcode
    const res3a = await fetch(`${baseUrl}/api/admin/hall-of-fame/${targetHofId}`, {
      method: 'PUT',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ playerName: 'Hacker' }),
    });
    assert(res3a.status === 401, 'Missing admin passcode returns 401 Unauthorized');

    // Test 3b: Wrong admin passcode
    const res3b = await fetch(`${baseUrl}/api/admin/hall-of-fame/${targetHofId}`, {
      method: 'PUT',
      headers: {
        'Content-Type': 'application/json',
        'x-admin-passcode': 'INCORRECT_PASSCODE_999',
      },
      body: JSON.stringify({ playerName: 'Hacker' }),
    });
    assert(res3b.status === 401, 'Invalid admin passcode returns 401 Unauthorized');

    console.log('\n👉 [Test 4] Nonexistent Entry');
    const res4 = await fetch(`${baseUrl}/api/admin/hall-of-fame/nonexistent-hof-entry-99999`, {
      method: 'PUT',
      headers: {
        'Content-Type': 'application/json',
        'x-admin-passcode': adminPasscode,
      },
      body: JSON.stringify({ playerName: 'Ghost Player' }),
    });
    const body4 = await res4.json();
    assert(res4.status === 404, 'Nonexistent ID returns 404 Not Found');
    assert(body4.success === false, 'Nonexistent ID response has success: false');

    // Restore baseline entry cleanly
    console.log('\n🧹 Restoring baseline entry playerName...');
    await dbService.updateHallOfFameEntry(targetHofId, {
      playerName: originalEntry.playerName,
      award: originalEntry.award,
      eventDate: originalEntry.eventDate,
      scoreDescription: originalEntry.scoreDescription,
    });
    console.log('✅ Baseline restored cleanly.\n');

  } finally {
    server.close();
  }

  if (allPassed) {
    console.log('🎉 ALL REGRESSION AND VALIDATION TESTS PASSED (100% SUCCESS)!\n');
    process.exit(0);
  } else {
    console.error('💥 SOME TESTS FAILED!\n');
    process.exit(1);
  }
}

runTests().catch((err) => {
  console.error('Unhandled test failure:', err);
  process.exit(1);
});
